"""Builds the naive C kernels and times them against NumPy.

The method borrows from the judge where that is cheap: C is timed inside C,
samples of the two contenders are interleaved, the median is reported, the
thread asks for the performance cores, and a reference loop is timed before and
after a run to detect a noisy machine. It is not the judge: there are no
confidence intervals, and one input per candidate.
"""
from __future__ import annotations

import ctypes
import logging
import math
import platform
import re
import statistics
import subprocess
import time
import timeit
from pathlib import Path
from typing import Callable

import numpy as np

from .candidates import HELPERS, Cand

log = logging.getLogger(__name__)

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
NAIVE_C = HERE / "naive.c"
# Build output. Not committed.
BUILD = ROOT / ".judge" / "survey"
LIBRARY = BUILD / "libnaive.dylib"

# The flags the judge uses for a kernel's naive.c.
CFLAGS = ["-O3", "-mcpu=native", "-std=c11", "-Wall", "-Wextra"]

# Element counts measured: one element (fixed cost only), then cache-resident
# sizes through to data far larger than any cache.
SIZES = [1, 16, 256, 4096, 65536, 1048576, 16777216]
# The largest size is the slow one; a quick run leaves it out.
QUICK_SIZES = SIZES[:-1]

# One timing sample repeats the call until it lasts at least this long.
MIN_SAMPLE_S = 0.005
# Calibration overshoots the target by this factor so it converges in few steps.
CALIBRATION_MARGIN = 1.2
# Upper bound on the repeat count, as a guard against a kernel optimised to nothing.
MAX_REPS = 1 << 30
# Shortest duration calibration trusts, so a zero reading cannot divide by zero.
MIN_MEASURABLE_S = 1e-9

# Samples per contender, and the time after which sampling stops early.
SAMPLES, BUDGET_S = 11, 4.0
QUICK_SAMPLES, QUICK_BUDGET_S = 5, 1.0
# Sampling never stops early with fewer samples than this.
MIN_SAMPLES = 5

# Every candidate draws its input from a generator with this seed.
SEED = 1234
NS_PER_S = 1e9

# The reference loop: a float64 sum over an array that fits in the L1 cache.
REFERENCE_N, REFERENCE_REPS, REFERENCE_RUNS, REFERENCE_SEED = 4096, 20000, 15, 0

# ctypes type for each letter of a candidate's signature.
CTYPES = {"p": ctypes.c_void_p, "i": ctypes.c_int64, "f": ctypes.c_float, "d": ctypes.c_double}

# clang's remark for a loop it vectorised: line number and vector width.
_VECTORISED = re.compile(r"naive\.c:(\d+):\d+: remark: vectorized loop \(vectorization width: (\d+)")
# A kernel generated by a macro: the remark points at the macro invocation,
# whose first argument is the kernel name.
_MACRO_KERNEL = re.compile(r"[A-Z_]+\((\w+)")
# A kernel written out by hand.
_PLAIN_KERNEL = re.compile(r"NOINLINE i64 (\w+)\(")
# How `pmset -g` reports that Low Power Mode is on.
_LOW_POWER_ON = re.compile(r"lowpowermode\s+1")


def ptr(a: np.ndarray) -> int:
    """Return the address of an array's first element.

    Args:
        a: Any NumPy array.

    Returns:
        The address as an integer, for passing to C as a pointer.
    """
    return a.ctypes.data


def build() -> ctypes.CDLL:
    """Compile naive.c into a shared library and load it.

    Returns:
        The loaded library, with the timing thread already moved to the
        highest scheduling class.
    """
    BUILD.mkdir(parents=True, exist_ok=True)
    subprocess.run(["clang", *CFLAGS, "-shared", "-o", str(LIBRARY), str(NAIVE_C)], check=True)
    lib = ctypes.CDLL(str(LIBRARY))
    lib.survey_init()
    return lib


def _kernel_at(source: list[str], line: int) -> str:
    """Find which kernel a line of naive.c belongs to.

    Args:
        source: The lines of naive.c.
        line: One-based line number from a clang remark.

    Returns:
        The kernel's name.
    """
    macro = _MACRO_KERNEL.match(source[line - 1])
    if macro:
        return macro.group(1)
    for text in reversed(source[:line]):
        plain = _PLAIN_KERNEL.match(text)
        if plain:
            return plain.group(1)
    raise ValueError(f"no kernel found above naive.c line {line}")


def vectorised() -> dict[str, list[str]]:
    """Ask clang which kernel loops its loop vectoriser vectorised.

    Returns:
        Kernel name -> one `line N: width W` entry per vectorised loop. A
        kernel that is missing has no vectorised loop. For a kernel with
        several loops, read the line number against naive.c to see which.
    """
    source = NAIVE_C.read_text().splitlines()
    remarks = subprocess.run(
        ["clang", *CFLAGS, "-c", "-o", "/dev/null", str(NAIVE_C),
         "-Rpass=loop-vectorize", "-fno-caret-diagnostics"],
        capture_output=True, text=True, check=True).stderr
    found: dict[str, list[str]] = {}
    for match in _VECTORISED.finditer(remarks):
        line, width = int(match.group(1)), match.group(2)
        found.setdefault(_kernel_at(source, line), []).append(f"line {line}: width {width}")
    return found


def calibrate(run: Callable[[int], float]) -> int:
    """Find a repeat count that makes one sample last at least MIN_SAMPLE_S.

    Args:
        run: Times the given number of calls and returns the seconds taken.

    Returns:
        The repeat count to use for every sample.
    """
    reps = 1
    while True:
        seconds = run(reps)
        if seconds >= MIN_SAMPLE_S or reps >= MAX_REPS:
            return reps
        scaled = math.ceil(reps * MIN_SAMPLE_S / max(seconds, MIN_MEASURABLE_S) * CALIBRATION_MARGIN)
        reps = max(reps * 2, scaled)


def environment_for(cand: Cand, n: int) -> dict:
    """Build the input a candidate is measured on.

    Args:
        cand: The candidate.
        n: Number of elements.

    Returns:
        The environment its expressions are evaluated in: `np`, `rng`, `n`,
        `ptr`, the helper functions, and everything the candidate's setup made.
    """
    env = {"np": np, "rng": np.random.default_rng(SEED), "n": n, "ptr": ptr, **HELPERS}
    for name, expression in cand.setup.items():
        env[name] = eval(expression, env)
    return env


def agrees(cand: Cand, env: dict) -> bool:
    """Check the naive C result against NumPy's.

    Args:
        cand: The candidate.
        env: Its environment, after the C kernel has run and `ret` is set.

    Returns:
        True when the two agree, exactly or within the candidate's tolerance.
    """
    got, expect = eval(cand.got, env), eval(cand.expect, env)
    if cand.rtol is None:
        return bool(np.array_equal(got, expect))
    return bool(np.allclose(got, expect, rtol=cand.rtol))


def measure(lib: ctypes.CDLL, cand: Cand, n: int, samples: int, budget_s: float) -> dict:
    """Check one candidate at one size, then time NumPy and naive C on it.

    Args:
        lib: The library from `build`.
        cand: The candidate.
        n: Number of elements.
        samples: Samples to take per contender.
        budget_s: Stop sampling early once this many seconds have passed.

    Returns:
        One result row: the candidate's identity, whether naive C agreed with
        NumPy, and the median and fastest time per call for each contender in
        nanoseconds.
    """
    env = environment_for(cand, n)
    args = [eval(expression, env) for expression in cand.args]
    signature = [CTYPES[letter] for letter in cand.sig]

    kernel = getattr(lib, cand.cfn)
    kernel.argtypes, kernel.restype = signature, ctypes.c_int64
    env["ret"] = kernel(*args)
    ok = agrees(cand, env)

    # A kernel with an output takes one more argument: the bytes to allocate
    # per call, or zero to write into the buffer it was given.
    fresh = [env[cand.out].nbytes if cand.alloc else 0] if cand.out else []
    bench = getattr(lib, "bench_" + cand.cfn)
    bench.argtypes = signature + [ctypes.c_int64] * (len(fresh) + 1)
    bench.restype = ctypes.c_uint64
    timer = timeit.Timer(cand.stmt, globals=env)

    def run_c(reps: int) -> float:
        """Time `reps` calls of the naive C kernel, in seconds."""
        return bench(*args, *fresh, reps) / NS_PER_S

    def run_numpy(reps: int) -> float:
        """Time `reps` executions of the NumPy statement, in seconds."""
        return timer.timeit(reps)

    reps_c, reps_numpy = calibrate(run_c), calibrate(run_numpy)
    c_ns, numpy_ns = [], []
    start = time.perf_counter()
    for taken in range(samples):
        numpy_ns.append(run_numpy(reps_numpy) / reps_numpy * NS_PER_S)
        c_ns.append(run_c(reps_c) / reps_c * NS_PER_S)
        if taken + 1 >= MIN_SAMPLES and time.perf_counter() - start > budget_s:
            break
    return {
        "key": cand.key, "group": cand.group, "stmt": cand.stmt, "cfn": cand.cfn,
        "n": n, "work": int(eval(cand.work, env)), "alloc": cand.alloc,
        "naive_matches_numpy": ok, "samples": len(c_ns),
        "numpy_ns": statistics.median(numpy_ns), "c_ns": statistics.median(c_ns),
        "numpy_min_ns": min(numpy_ns), "c_min_ns": min(c_ns),
        "numpy_over_c": statistics.median(numpy_ns) / statistics.median(c_ns),
    }


def reference_ns(lib: ctypes.CDLL) -> float:
    """Time the fixed reference loop.

    Args:
        lib: The library from `build`.

    Returns:
        The fastest time per call in nanoseconds. Comparing the value before
        and after a run shows whether the machine's speed drifted.
    """
    x = np.random.default_rng(REFERENCE_SEED).random(REFERENCE_N)
    result = np.empty(1)
    bench = lib.bench_sum_f64
    bench.argtypes = [ctypes.c_void_p, ctypes.c_int64, ctypes.c_int64, ctypes.c_void_p, ctypes.c_int64]
    bench.restype = ctypes.c_uint64
    return min(bench(ptr(x), REFERENCE_N, 1, ptr(result), REFERENCE_REPS) / REFERENCE_REPS
               for _ in range(REFERENCE_RUNS))


def _output_of(command: list[str]) -> str:
    """Run a command and return what it printed.

    Args:
        command: The program and its arguments.

    Returns:
        Standard output with surrounding whitespace removed; empty if the
        command failed.
    """
    return subprocess.run(command, capture_output=True, text=True).stdout.strip()


def describe_machine(kernels: list[str], drift: float) -> dict:
    """Record what a run was measured on.

    Args:
        kernels: Names of the C kernels that were measured.
        drift: Relative change of the reference loop over the run.

    Returns:
        The metadata stored beside the result rows: processor, operating
        system, compiler, NumPy and Python versions, git revision, the
        reference drift, and which kernels clang vectorised.
    """
    loops = vectorised()
    return {
        "cpu": _output_of(["sysctl", "-n", "machdep.cpu.brand_string"]),
        "os": platform.platform(),
        "clang": _output_of(["clang", "--version"]).splitlines()[0],
        "cflags": CFLAGS,
        "numpy": np.__version__,
        "python": platform.python_version(),
        "low_power_mode": bool(_LOW_POWER_ON.search(_output_of(["pmset", "-g"]))),
        "reference_drift": drift,
        "git": _output_of(["git", "-C", str(ROOT), "rev-parse", "HEAD"]),
        "c_vectorised": {name: loops.get(name, []) for name in sorted(kernels)},
    }
